def cases_for_role(role_key: str) -> list[dict[str, Any]]:
    out = [c for c in CASES if c["role_key"] == role_key]
    return out or CASES[:1]


# ─────────────────────────────────────────────────────────────────────────────
# Генерация вариации кейса под требования вакансии
