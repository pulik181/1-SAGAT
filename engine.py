def build_case(role_key: str, variant: int = 0, vacancy: dict[str, Any] | None = None) -> dict[str, Any]:
    """Собирает конкретный экземпляр кейса.

    Библиотека даёт базовый сценарий, требования вакансии переписывают ограничения
    и текст смены вводных. Это та же схема, которую в Roadmap выполняет LLM API, —
    здесь она реализована шаблонами, поэтому результат воспроизводим.
    """
    pool = cases_for_role(role_key)
    base = dict(pool[variant % len(pool)])
    case = {
        "key": base["key"],
        "role_key": base["role_key"],
        "role_title": ROLES[base["role_key"]]["title"],
        "title": base["title"],
        "client": base["client"],
        "task": base["task"],
        "constraints": list(base["constraints"]),
        "inject": base["inject"],
        "expected": list(base["expected"]),
        "inject_enabled": True,
        "duration_min": 60,
    }

    if vacancy:
        stack = (vacancy.get("stack") or "").strip()
        budget = vacancy.get("budget")
        days = vacancy.get("days")
        local = vacancy.get("local_data")
        cons: list[str] = []
        if budget:
            cons.append(f"бюджет ${int(budget)}/мес")
        if days:
            cons.append(f"срок {int(days)} дней")
        if stack:
            cons.append(stack)
        cons.append("без собственных GPU" if role_key == "ai" else "без новых внешних сервисов")
        if local:
            cons.append("данные не покидают РК")
        case["constraints"] = cons
        case["title"] = f"{base['title']} · {vacancy.get('title') or ROLES[role_key]['title']}"
        case["inject_enabled"] = bool(vacancy.get("inject_on", True))
        if budget:
            cut = max(40, int(int(budget) * 0.3))
            case["inject"] = (
                f"Заказчик урезал бюджет до ${cut}/мес и требует ответ быстрее 2 секунд на 95-м "
                "перцентиле. Обновите решение и объясните, чем именно вы жертвуете."
                if role_key == "ai"
                else (
                    f"Заказчик сократил бюджет до ${cut}/мес и добавил новое требование в середине "
                    "срока. Обновите решение и объясните, что вы урезаете и почему."
                )
            )
    return case


def case_terms(case_key: str) -> tuple[list[str], list[str]]:
    base = CASE_BY_KEY.get(case_key) or CASES[0]
    return base["constraint_terms"], base["adapt_terms"]


