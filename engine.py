WEIGHTS = {"logic": 25, "tech": 25, "constraints": 20, "adaptivity": 15, "defense": 15}
PENALTY_MAX = 12

CRIT_TITLES = {
    "logic": "Логика и декомпозиция",
    "tech": "Техническая корректность",
    "constraints": "Соблюдение ограничений",
    "adaptivity": "Адаптивность к смене вводных",
    "defense": "Защита решения (Live Defense)",
}


def _norm(text: str) -> str:
    return unicodedata.normalize("NFKC", text or "").lower()


def _count(text: str, terms: list[str]) -> list[str]:
    return sorted({t for t in terms if t in text})


def _clamp(v: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, v))


def _plural(n: int, one: str, few: str, many: str) -> str:
    n = abs(int(n)) % 100
    if 11 <= n <= 14:
        return many
    n %= 10
    if n == 1:
        return one
    if 2 <= n <= 4:
        return few
    return many


def score_attempt(
    *,
    role_key: str,
    case_key: str,
    answer: str,
    tail: str,
    defense_answers: list[str],
    telemetry: dict[str, Any],
    inject_enabled: bool = True,
) -> dict[str, Any]:
    """Возвращает результат по строгой JSON-схеме рубрикатора."""
    text = _norm(answer)
    tail_text = _norm(tail)
    constraint_terms, adapt_terms = case_terms(case_key)
    tech_terms = ROLE_TECH.get(role_key, ROLE_TECH["ai"])

    # --- структура решения ---
    blocks = [b for b in re.split(r"\n{1,}|(?:^|\n)\s*[-–—•*]\s+", answer or "") if len(b.strip()) > 14]
    sentences = [s for s in re.split(r"[.!?]\s+", answer or "") if len(s.strip()) > 18]
    logic_hits = _count(text, LOGIC_MARKERS)
    words = len(re.findall(r"[\w’'-]+", answer or ""))

    logic_raw = (
        len(logic_hits) * 1.55
        + min(6.0, len(blocks) * 1.5)
        + min(4.5, len(sentences) * 0.6)
        + min(4.5, words / 70)
    )
    logic = round(_clamp(logic_raw, 0, WEIGHTS["logic"]))

    tech_hits = _count(text, tech_terms)
    tech_raw = len(tech_hits) * 2.0 + min(4.0, words / 110)
    tech = round(_clamp(tech_raw, 0, WEIGHTS["tech"]))

    con_hits = _count(text, constraint_terms)
    numbers = re.findall(r"\d[\d\s.,]*", answer or "")
    con_raw = len(con_hits) * 2.25 + min(3.5, len(numbers) * 0.8)
    constraints = round(_clamp(con_raw, 0, WEIGHTS["constraints"]))

    if inject_enabled:
        ad_hits = _count(tail_text, adapt_terms)
        ad_raw = len(ad_hits) * 2.5 + (3.5 if len(tail_text) > 220 else 2.0 if len(tail_text) > 70 else 0.0)
        adaptivity = round(_clamp(ad_raw, 0, WEIGHTS["adaptivity"]))
    else:
        ad_hits = []
        adaptivity = round(WEIGHTS["adaptivity"] * 0.6)

    answered = [a for a in (defense_answers or []) if len(a.strip()) >= 25]
    joined = _norm(" ".join(defense_answers or []))
    depth_hits = _count(joined, DEFENSE_DEPTH)
    def_raw = len(answered) * 3.1 + min(3.0, len(depth_hits) * 0.7) + min(2.0, len(joined) / 300)
    defense = round(_clamp(def_raw, 0, WEIGHTS["defense"]))

    paste = int(telemetry.get("paste") or 0)
    blur = int(telemetry.get("blur") or 0)
    idle = int(telemetry.get("idle") or 0)
    penalty = int(min(PENALTY_MAX, paste * 5 + blur * 2 + max(0, idle - 2)))

    raw = logic + tech + constraints + adaptivity + defense
    total = int(max(0, min(100, raw - penalty)))

    if total >= 72:
        badge, badge_label = "verified", "Verified Skill Badge · выдан"
    elif total >= 45:
        badge, badge_label = "partial", "Verified Skill Badge · частично"
    else:
        badge, badge_label = "none", "Бейдж не выдан"

    missing_con = [t for t in constraint_terms if t not in text and not t.startswith("$")][:5]

    criteria = [
        {
            "key": "logic",
            "title": CRIT_TITLES["logic"],
            "score": logic,
            "max": WEIGHTS["logic"],
            "evidence": f"Смысловых блоков: {len(blocks)}, связок обоснования: {len(logic_hits)}, слов: {words}.",
            "matched": logic_hits[:8],
            "recommendation": (
                "Решение читается как последовательность решений с обоснованием."
                if logic >= 18
                else "Разбейте ответ на явные шаги и на каждом скажите «выбираю X, потому что Y» — сейчас связок обоснования мало."
            ),
        },
        {
            "key": "tech",
            "title": CRIT_TITLES["tech"],
            "score": tech,
            "max": WEIGHTS["tech"],
            "evidence": f"Профильных механизмов затронуто: {len(tech_hits)}. Область: {ROLE_TECH_LABELS.get(role_key, '')}.",
            "matched": tech_hits[:10],
            "recommendation": (
                "Технический уровень соответствует роли."
                if tech >= 18
                else (
                    "Не хватает конкретных механизмов. Назовите инструменты и приёмы по темам: "
                    + ROLE_TECH_LABELS.get(role_key, "профильные механизмы роли")
                    + " — и на каждом объясните, зачем он здесь."
                )
            ),
        },
        {
            "key": "constraints",
            "title": CRIT_TITLES["constraints"],
            "score": constraints,
            "max": WEIGHTS["constraints"],
            "evidence": f"Ограничений задания упомянуто: {len(con_hits)}, числовых величин: {len(numbers)}.",
            "matched": con_hits[:10],
            "recommendation": (
                "Ограничения заказчика учтены явно и с цифрами."
                if constraints >= 14
                else "Вернитесь к рамкам задания: бюджет, срок, стек и требования к данным должны быть названы числами, а не «дешёвым решением»."
            ),
        },
        {
            "key": "adaptivity",
            "title": CRIT_TITLES["adaptivity"],
            "score": adaptivity,
            "max": WEIGHTS["adaptivity"],
            "evidence": (
                f"После смены вводных дописано символов: {len(tail_text)}, отработано релевантных пунктов: {len(ad_hits)}."
                if inject_enabled
                else "Проверка на смену вводных отключена в настройках отбора."
            ),
            "matched": ad_hits[:8],
            "recommendation": (
                "Смена требований отработана осознанно, компромисс назван."
                if adaptivity >= 11
                else "После смены вводных нужно прямо сказать, что вы урезаете и что теряет пользователь, — общая фраза «оптимизирую» не считается."
            ),
        },
        {
            "key": "defense",
            "title": CRIT_TITLES["defense"],
            "score": defense,
            "max": WEIGHTS["defense"],
            "evidence": f"Содержательно отвечено на {len(answered)} из {max(1, len(defense_answers or []))} вопросов ИИ-интервьюера.",
            "matched": depth_hits[:8],
            "recommendation": (
                "Автор подтвердил понимание собственного решения."
                if defense >= 11
                else "В защите отвечайте измеримо: назовите сигнал, порог и способ проверки, а не общее описание."
            ),
        },
    ]

    flags: list[str] = []
    if paste:
        flags.append(f"Попытки вставки из буфера: {paste}")
    if blur >= 3:
        flags.append(f"Потеря фокуса окна: {blur}")
    if idle >= 4:
        flags.append(f"Пауз дольше 20 секунд: {idle}")
    if telemetry.get("cpm") and int(telemetry["cpm"]) > 900:
        flags.append("Аномально высокий ритм ввода")

    if badge == "verified":
        verdict = (
            "Решение структурно целостное, ограничения учтены числами, смена вводных отработана "
            "осознанно, авторство подтверждено защитой. Кандидат попадает в верхнюю часть shortlist — "
            "рекомендуем технический разговор без дополнительного тестового задания."
        )
    elif badge == "partial":
        verdict = (
            "База есть, но часть ограничений и компромиссов не проговорена явно. Для HR это середина "
            "shortlist: потенциал виден, требуется адресная проверка пробелов на интервью. Кандидат "
            "получил разбор по каждому критерию."
        )
    else:
        verdict = (
            "Решение слишком поверхностное, чтобы считаться доказательством навыка: ограничения не "
            "отражены, защита не подтвердила логику. Кандидату выдана карта слабых мест и рекомендация "
            "повторить симуляцию; в shortlist компании он не попадает."
        )
    if paste:
        verdict += f" Зафиксировано {paste} {_plural(paste, 'попытка', 'попытки', 'попыток')} вставки из буфера — балл снижен, флаг передан в карточку."

    strengths = [c["title"] for c in criteria if c["score"] >= c["max"] * 0.72]
    gaps = [c["title"] for c in criteria if c["score"] < c["max"] * 0.5]

    next_steps: list[str] = []
    for c in criteria:
        if c["score"] < c["max"] * 0.6:
            next_steps.append(c["recommendation"])
    if not next_steps:
        next_steps.append(
            "Сильный результат. Следующий шаг — усложнённая симуляция того же профиля с более жёстким бюджетом."
        )

    fingerprint = hashlib.sha256(
        json.dumps([role_key, case_key, total, [c["score"] for c in criteria], penalty], ensure_ascii=False).encode()
    ).hexdigest()[:16]

    return {
        "rubric_version": RUBRIC_VERSION,
        "role_key": role_key,
        "case_key": case_key,
        "total": total,
        "raw": int(raw),
        "penalty": penalty,
        "badge": badge,
        "badge_label": badge_label,
        "criteria": criteria,
        "flags": flags,
        "verdict": verdict,
        "strengths": strengths,
        "gaps": gaps,
        "next_steps": next_steps[:3],
        "telemetry": {"paste": paste, "blur": blur, "idle": idle, "cpm": int(telemetry.get("cpm") or 0), "chars": int(telemetry.get("chars") or len(answer or ""))},
        "fingerprint": fingerprint,
    }
